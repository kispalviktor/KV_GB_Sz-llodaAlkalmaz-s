CREATE DATABASE IF NOT EXISTS SzallodaDb DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_hungarian_ci;
USE SzallodaDb;

DROP TABLE IF EXISTS Bookings;
DROP TABLE IF EXISTS Guests;
DROP TABLE IF EXISTS Rooms;

CREATE TABLE Rooms (
    RoomNumber INT PRIMARY KEY,
    RoomType VARCHAR(50) NOT NULL,
    Capacity INT NOT NULL,
    PricePerNight DECIMAL(10, 2) NOT NULL,
    Equipment TEXT,
    IsActive BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE Guests (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    Name VARCHAR(100) NOT NULL,
    Phone VARCHAR(20) NOT NULL,
    Email VARCHAR(100) NOT NULL
);

CREATE TABLE Bookings (
    Id INT AUTO_INCREMENT PRIMARY KEY,
    GuestId INT NOT NULL,
    RoomNumber INT NOT NULL,
    CheckIn DATE NOT NULL,
    CheckOut DATE NOT NULL,
    GuestCount INT NOT NULL,
    Status VARCHAR(50) NOT NULL DEFAULT 'Aktív',
    TotalPrice DECIMAL(10, 2) NOT NULL,
    FOREIGN KEY (GuestId) REFERENCES Guests(Id) ON DELETE RESTRICT ON UPDATE CASCADE,
    FOREIGN KEY (RoomNumber) REFERENCES Rooms(RoomNumber) ON DELETE RESTRICT ON UPDATE CASCADE
);

